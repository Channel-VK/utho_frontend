export function generate30dTimeSeries(resource: Resource) {
  const points: { timestamp: string; cpu_pct: number; mem_pct: number; disk_iops: number; net_mbps: number }[] = [];
  const baseCpu = resource.metrics_summary.cpu_avg;
  const p95Cpu = resource.metrics_summary.cpu_p95;
  const p99Cpu = resource.metrics_summary.cpu_p99;
  const baseMem = resource.metrics_summary.mem_avg;

  for (let i = 30; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const dayStr = d.toISOString().split('T')[0];

    // Create 4 data points per day (every 6 hours)
    for (let h = 0; h < 24; h += 6) {
      const timeStr = `${dayStr} ${String(h).padStart(2, '0')}:00`;
      const isPeakHour = h === 18; // evening burst
      let cpu = baseCpu + (Math.sin(i * 0.8 + h) * 4);
      if (resource.optimization_status === 'PROTECTED_PEAK_LOAD') {
        if (isPeakHour) {
          cpu = (i % 3 === 0) ? p99Cpu : p95Cpu;
        } else {
          cpu = baseCpu + Math.random() * 5;
        }
      } else if (resource.optimization_status === 'ZOMBIE') {
        cpu = 0.1 + Math.random() * 0.1;
      } else {
        cpu = Math.min(cpu, p99Cpu);
      }

      let mem = baseMem + (Math.cos(i * 0.5 + h) * 3);
      if (resource.name.includes('indexer-04')) {
        // Memory leak trend
        mem = Math.min(96, 40 + (30 - i) * 1.8);
      }

      points.push({
        timestamp: timeStr,
        cpu_pct: Number(Math.max(0.1, Math.min(100, cpu)).toFixed(1)),
        mem_pct: Number(Math.max(1, Math.min(100, mem)).toFixed(1)),
        disk_iops: Math.round(resource.metrics_summary.disk_iops_avg + (isPeakHour ? resource.metrics_summary.disk_iops_p95 * 0.4 : 0)),
        net_mbps: Number((resource.metrics_summary.net_mbps_avg * (isPeakHour ? 1.8 : 0.9)).toFixed(1)),
      });
    }
  }

  return points;
}

